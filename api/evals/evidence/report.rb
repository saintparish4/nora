module EvidenceEval
  # Human-readable views built from the case files and from a round's traces.
  # Nothing here computes a score that the per-case rows do not already hold.
  module Report
    module_function

    VERDICTS = { "support" => "supports the criterion", "noise" => "does not support it (the requirement is supported by other text)",
                 "trap" => "FALSE PROPOSAL (a known trap)", "false" => "FALSE PROPOSAL", "unscored" => "not scored" }.freeze

    # Every case in full: the sign-off view for the cases and their labels.
    def review
      cases = prepared_cases
      state = STATE_PATH.exist? ? JSON.parse(STATE_PATH.read) : {}
      lines = [ "# Evidence eval: every case", "",
                "Generated by `bin/rails eval:evidence:review` from `cases/*.yml`. Edit the case files, not this file.", "",
                "Each case is one request. For every payer criterion the label says whether the chart, read by a person,",
                "supports it. `support` is the text that does. `traps` is text that looks relevant and is not enough.", "",
                "| # | case | tags | medication, plan | supported | unsupported | not scored | slice |", "|---|---|---|---|---|---|---|---|" ]
      cases.each.with_index(1) do |c, i|
        slice = state.fetch("test_ids", []).include?(c.id) ? "test" : "train"
        lines << "| #{i} | `#{c.id}` | #{c.tags.join(', ')} | #{c.item}, #{c.coverage['payer']} | #{c.positions('supported').size} | " \
                 "#{c.positions('unsupported').size} | #{(c.positions('not_applicable') + c.positions('ambiguous')).size} | #{slice} |"
      end
      totals = LABELS.to_h { |label| [ label, cases.sum { |c| c.positions(label).size } ] }
      lines << "" << "Totals over #{cases.size} cases: " + totals.map { |label, n| "#{n} #{label.tr('_', ' ')}" }.join(", ") + "." << ""

      cases.each.with_index(1) do |c, i|
        criteria = Library.template_for(c).criteria.index_by(&:position)
        lines << "## #{i}. `#{c.id}`" << "" << "#{c.item} for #{c.patient['first_name']} #{c.patient['last_name']}, #{c.coverage['payer']} #{c.coverage['plan']}. " \
                                                "Request dated #{c.as_of}. Tags: #{c.tags.join(', ')}." << ""
        c.documents.each do |doc|
          lines << "**#{doc['title']}** (#{doc['kind'].tr('_', ' ')}, #{doc['occurred_on']})" << "" << "```text" << doc["body"] << "```" << ""
        end
        lines << "| criterion | label | support / traps | why |" << "|---|---|---|---|"
        c.expected.keys.sort.each do |position|
          entry = c.expected[position]
          quotes = Array(entry["support"]).map { |q| "support: \"#{cell(q)}\"" } + Array(entry["traps"]).map { |q| "trap: \"#{cell(q)}\"" }
          lines << "| #{position}. #{cell(criteria.fetch(position).text)} | **#{entry['label'].tr('_', ' ')}** | #{quotes.join('<br>')} | #{cell(entry['why'].to_s)} |"
        end
        lines << ""
      end
      ROOT.join("REVIEW.md").write(lines.join("\n"))
      puts "wrote #{ROOT.join('REVIEW.md').relative_path_from(Rails.root)} (#{cases.size} cases)"
    end

    # Graded examples from the train slice only. Whoever changes the system
    # next reads failures from train; the test slice stays unread.
    def graded(round, limit: 8)
      train = JSON.parse(STATE_PATH.read).fetch("train_ids")
      traces = train.filter_map { |id| ROOT.join(round, "traces", "#{id}_rep0.json") }.select(&:exist?).map { |path| JSON.parse(path.read) }
      # One per primary tag first, so the handful covers different shapes.
      chosen = traces.group_by { |t| t["tags"].first }.values.map(&:first).first(limit)
      lines = [ "# Evidence eval: graded examples (#{round}, train slice)", "",
                "Generated by `bin/rails eval:evidence:graded`. For each criterion: the label a person gave, what the system",
                "proposed, and how the grader scored each excerpt. The question for the owner: would you have scored any of",
                "these differently?", "" ]
      chosen.each do |trace|
        grade = trace["grade"].map { |k, v| "#{k} #{v.nil? ? 'n/a' : v}" }.join(", ")
        lines << "## `#{trace['case_id']}`" << "" << "#{trace['item']}, #{trace.dig('coverage', 'payer')}. Case grade: #{grade}." << ""
        trace["documents"].each { |doc| lines << "**#{doc['title']}** (#{doc['occurred_on']})" << "" << "```text" << doc["body"] << "```" << "" }
        trace["requirements"].each do |req|
          criterion = trace.dig("criteria", req["position"].to_s, "text")
          lines << "**#{req['position']}. #{criterion}**" << ""
          lines << "- Label: **#{req['label'].tr('_', ' ')}**#{req['why'] ? ". #{req['why']}" : ''}"
          result =
            case req["label"]
            when "supported" then req["found"] ? "found" : "MISSED: nothing proposed supports it"
            when "unsupported" then req["proposals"].empty? ? "clean: nothing proposed" : "NOT CLEAN: #{req['proposals'].size} proposed"
            else "not scored"
            end
          lines << "- Grade: #{result}"
          req["proposals"].each do |p|
            lines << "  - \"#{p['excerpt'].tr("\n", ' ')}\" (#{p['source']}): #{VERDICTS.fetch(p['verdict'])}"
          end
          lines << ""
        end
      end
      ROOT.join("GRADED.md").write(lines.join("\n"))
      puts "wrote #{ROOT.join('GRADED.md').relative_path_from(Rails.root)} (#{chosen.size} train cases)"
    end

    # Totals recomputed from the traces by a different path than the per-case
    # means: pooled over requirements rather than averaged over cases.
    def summary(round)
      traces = ROOT.join(round, "traces").glob("*_rep0.json").sort.map { |path| JSON.parse(path.read) }
      abort "no traces under #{round}" if traces.empty?

      requirements = traces.flat_map { |t| t["requirements"].map { |r| r.merge("criterion_kind" => t.dig("criteria", r["position"].to_s, "kind")) } }
      supported = requirements.select { |r| r["label"] == "supported" }
      unsupported = requirements.select { |r| r["label"] == "unsupported" }
      excerpts = (supported + unsupported).flat_map { |r| r["proposals"] }
      errors = ROOT.join(round, "errors.jsonl")

      puts "#{round}: #{traces.size} cases, #{errors.exist? ? errors.readlines.size : 0} errored attempts (not scored)"
      puts "pooled over requirements (a second path; the headline is the per-case mean from score.py):"
      puts format("  found      %3d of %3d supported requirements", supported.count { |r| r["found"] }, supported.size)
      puts format("  clean      %3d of %3d unsupported requirements", unsupported.count { |r| r["proposals"].empty? }, unsupported.size)
      puts format("  precision  %3d of %3d proposed excerpts support their criterion", excerpts.count { |p| p["verdict"] == "support" }, excerpts.size)
      puts "by criterion position (found / supported, clean / unsupported):"
      requirements.group_by { |r| r["position"] }.sort.each do |position, group|
        sup = group.select { |r| r["label"] == "supported" }
        unsup = group.select { |r| r["label"] == "unsupported" }
        puts format("  %d %-17s found %2d/%-2d  clean %2d/%-2d", position, group.first["criterion_kind"], sup.count { |r| r["found"] }, sup.size,
                    unsup.count { |r| r["proposals"].empty? }, unsup.size)
      end
      puts "by source (excerpts proposed / that support / false proposals on unsupported requirements):"
      excerpts.group_by { |p| p["source"] }.sort.each do |source, group|
        puts format("  %-6s %3d / %3d / %3d", source, group.size, group.count { |p| p["verdict"] == "support" }, group.count { |p| %w[trap false].include?(p["verdict"]) })
      end
    end

    # Cases checked against the policy library in the scratch database.
    def prepared_cases
      runner = Runner.new(round: "review", out: StringIO.new)
      runner.send(:prepare_database)
      cases = Case.load_all
      Library.check_labels_cover_criteria!(cases)
      cases
    end

    def cell(text) = text.gsub("|", "\\|").tr("\n", " ")
  end
end
